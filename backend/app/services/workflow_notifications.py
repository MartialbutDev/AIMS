"""Persist workflow notifications atomically, without network calls or commits.

Only production API sessions opt in. ORM history prevents alerts for unchanged
fields, and rollback also rolls back every notification generated by that change.
"""
import json
import uuid
from sqlalchemy import inspect
from app.models.notification import Notification, NotificationType
from app.services.notification_scope import NotificationScope, destinations, value


def enqueue(db, recipients, kind, title, message, data=None, scope=None, exclude_actor=True):
    scope = scope or NotificationScope(db)
    event_id = str(uuid.uuid4())
    actor = db.info.get('notification_actor_id') if exclude_actor else None
    for uid in set(recipients) - {None, actor}:
        user = scope.users.get(uid)
        if user is None: continue
        payload = {'event_id': event_id, **(data or {})}
        payload.update(destinations(user.role, kind, payload.get('source', 'workflow')))
        db.add(Notification(id=str(uuid.uuid4()), user_id=uid, type=NotificationType(kind),
                            title=title[:255], message=message, data=json.dumps(payload), is_read=False))


def capture(db, flush_context, instances):
    if not db.info.get('workflow_notifications'): return
    changes = list(db.new) + list(db.dirty) + list(db.deleted)
    if not any(o.__class__.__name__ in WATCHED for o in changes): return
    scope = NotificationScope(db)
    for obj in changes:
        name = obj.__class__.__name__
        if name not in WATCHED: continue
        if obj in db.deleted:
            if name == 'CoordinatorStudentAssignment':
                enqueue(db, {obj.student_id, obj.coordinator_id}, 'system', 'Coordinator assignment removed', 'A semester assignment was removed. Contact school support if reassignment is needed.', scope=scope)
            continue
        year, semester = getattr(obj, 'academic_year', None), getattr(obj, 'semester', None)
        if year and semester and (str(year), str(semester)) != scope.term: continue
        state = inspect(obj)
        new = state.pending
        def changed(field):
            return new or state.attrs[field].history.has_changes()
        def emit(users, kind, title, message, **payload):
            enqueue(db, users, kind, title, message, payload, scope)
        sid = getattr(obj, 'student_id', None)
        staff = scope.coordinators[sid]
        student_name = ' '.join([scope.users[sid].first_name, scope.users[sid].last_name]) if sid in scope.users else 'A student'
        if name in {'Application', 'DTR', 'Journal'}:
            if not changed('status') and not (name == 'Journal' and changed('feedback')): continue
            status = value(obj.status) or ('pending' if name != 'Journal' else 'draft')
            if name == 'Journal' and status == 'draft': continue
            kind = {'Application': 'application', 'DTR': 'dtr', 'Journal': 'journal'}[name]
            if not obj.id: obj.id = str(uuid.uuid4())
            recipients = {sid} | staff
            if name == 'DTR' and status == 'pending': recipients = {sid}
            if name in {'DTR', 'Journal'} and status in {'submitted', 'approved', 'rejected'}:
                recipients |= scope.monitoring_users(sid, getattr(obj, 'date', None) if name == 'DTR' else getattr(obj, 'submitted_date', None))
            if name == 'Application' and status in {'endorsed', 'accepted', 'rejected'}:
                recipients |= scope.roles['career_center']
                if status == 'accepted': recipients |= scope.deans[sid]
            if name == 'Application' and status in {'endorsed', 'interview', 'accepted', 'withdrawn', 'rejected'}:
                recipients |= scope.supervisors[obj.company_id]
            # Company monitoring is read-only: school review remains with the coordinator.
            emit(recipients, kind, f'{name if name != "DTR" else "DTR"}: {status.replace("_", " ")}',
                 f'{student_name} — {kind} status is now {status.replace("_", " ")}. Open the related record for details.',
                 **{f'{kind}_id': obj.id}, status=status, student_id=sid)
        elif name == 'Document':
            if not changed('verification_status'): continue
            sid = obj.uploaded_by
            if not obj.id: obj.id = str(uuid.uuid4())
            status = value(obj.verification_status) or 'pending'
            emit({sid} | scope.coordinators[sid], 'document', f'Document: {status}',
                 'A student document was uploaded or reviewed. Open Documents to see the result and any feedback.',
                 document_id=obj.id, status=status, student_id=sid)
        elif name == 'StudentOnboardingSubmission':
            if not changed('review_status'): continue
            status = obj.review_status or 'pending_review'
            emit({sid} | staff | scope.roles['admin'], 'document', f'Onboarding: {status.replace("_", " ")}',
                 'An onboarding submission needs attention or has a review decision.', source='onboarding', status=status, student_id=sid)
        elif name == 'InternshipDeployment':
            if getattr(obj, '_completion_workflow', False): continue
            if not changed('status'): continue
            status = value(obj.status) or 'pre_deployment'
            if status == 'pre_deployment': continue  # Application acceptance already supplies this alert.
            emit({sid} | staff | scope.deans[sid] | scope.supervisors[obj.company_id], 'application',
                 f'Internship {status}', f'{student_name} — internship status is now {status}.',
                 source='deployment', status=status, student_id=sid, deployment_id=obj.id)
        elif name == 'CoordinatorStudentAssignment':
            if not changed('coordinator_id'): continue
            recipients = {sid, obj.coordinator_id} | scope.deans[sid] | scope.designations[obj.coordinator_id]
            recipients.update(state.attrs.coordinator_id.history.deleted)
            emit(recipients, 'system', 'Coordinator assignment updated',
                 f'{student_name} has an updated coordinator assignment. Review the current semester workspace.', student_id=sid)
        elif name == 'DeanCoordinatorDesignation':
            if not (changed('is_active') or changed('coordinator_id')): continue
            emit({obj.coordinator_id, obj.assigned_by_dean_id}, 'system', 'Coordinator designation updated',
                 'A coordinator designation has changed. Review your access and assignments for the semester.')
        elif name == 'HTESupervisorCompany':
            if not (changed('is_active') or changed('company_id')): continue
            emit({obj.supervisor_id} | scope.roles['career_center'], 'system', 'Company access updated',
                 'A company supervisor assignment has changed. Review your company workspace.')
        elif name == 'Company':
            fields = ['is_active', 'is_moa_signed', 'moa_reference', 'moa_signed_at', 'moa_effective_at', 'moa_expires_at']
            if not (new or any(changed(f) for f in fields if f in state.attrs)): continue
            recipients = scope.roles['career_center'] | scope.roles['admin'] | scope.supervisors[obj.id]
            from app.models.direct_placement import DirectPlacement
            if inspect(db.connection()).has_table('direct_placements'):
                for proposal in db.query(DirectPlacement).filter_by(company_id=obj.id, academic_year=scope.term[0], semester=scope.term[1]):
                    if proposal.status in {'pending', 'released'}:
                        recipients |= {proposal.student_id, proposal.coordinator_id, proposal.proposed_by} | scope.deans[proposal.student_id]
            emit(recipients, 'system',
                 'Company partnership updated', 'Company registration or partnership details have changed. Review the company record.')
        elif name == 'DocumentTemplateRevision':
            if not new: continue
            from app.models.document_template import DocumentTemplateSeries
            series = next((s for s in changes if s.__class__.__name__ == 'DocumentTemplateSeries' and s.id == obj.series_id), None) or db.get(DocumentTemplateSeries, obj.series_id)
            if series and (str(series.academic_year), str(series.semester)) == scope.term:
                users = {s for s, coords in scope.coordinators.items() if series.coordinator_id in coords}
                emit(users, 'document', 'Approved CITC form published', f'{obj.title} · Version {obj.version}. Download the form and check its instructions and deadline.', source='document_template', template_id=obj.id, deadline_at=str(obj.deadline) if obj.deadline else None)
        elif name == 'DocumentTemplateSeries':
            if not new and changed('withdrawn_at') and obj.withdrawn_at:
                users = {s for s, coords in scope.coordinators.items() if obj.coordinator_id in coords}
                emit(users, 'document', 'CITC form withdrawn', 'A published form has been withdrawn. Check Approved CITC forms for the current version.', source='document_template')
        elif name == 'CoordinatorEvaluation':
            if not new and not any(state.attrs[f].history.has_changes() for f in state.attrs.keys() if f not in {'id', 'updated_at'}): continue
            emit({sid} | scope.deans[sid], 'system', 'Internship evaluation updated',
                 'An internship evaluation was recorded or updated. Review your authorized academic workspace.', student_id=sid)
        elif name == 'DirectPlacementEvent':
            if not new or obj.action.startswith('application_') or obj.action == 'released_to_company': continue
            from app.models.direct_placement import DirectPlacement
            p = next((p for p in changes if p.__class__.__name__ == 'DirectPlacement' and p.id == obj.placement_id), None) or db.get(DirectPlacement, obj.placement_id)
            if p:
                recipients = {p.student_id, p.coordinator_id, p.proposed_by} | scope.deans[p.student_id]
                if p.partnership_status != 'cleared' or 'partnership' in obj.action:
                    recipients |= scope.roles['career_center']
                emit(recipients, 'application', 'Direct placement update',
                     f'Placement action: {obj.action.replace("_", " ")}. Open the placement to review its status and next steps.', source='direct_placement', placement_id=p.id, student_id=p.student_id)


WATCHED = {'Application', 'DTR', 'Journal', 'Document', 'StudentOnboardingSubmission',
           'InternshipDeployment', 'CoordinatorStudentAssignment', 'DeanCoordinatorDesignation',
           'HTESupervisorCompany', 'Company', 'DocumentTemplateRevision', 'DocumentTemplateSeries',
           'CoordinatorEvaluation', 'DirectPlacementEvent'}
